export function useTranslations(languageCode: string) {
  const getLang = () => {
    if (UI_STRINGS[languageCode]) return languageCode;
    return 'en-IN'; // Fallback
  };

  const t = (key: string): string => {
    const lang = getLang();
    return UI_STRINGS[lang][key] || UI_STRINGS['en-IN'][key] || key;
  };

  return { t };
}
